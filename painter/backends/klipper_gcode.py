"""PaintProgram -> Klipper G-code.

Axes: X/Y gantry, Z brush height (pressure), A brush rotation in degrees. The A axis is expected to be a Klipper
`manual_stepper` registered as an extra G-code axis (`gcode_axis: A`, see klipper/macros.cfg).
Station routines (tool change, dip, wash, wipe, refill pause) are macro calls so their motion can be tuned on the
machine without regenerating programs.
"""

from __future__ import annotations

from painter.config import MachineConfig
from painter.program import Dip, Paint, PaintProgram, Pause, ToolChange, Wash, Wipe


def _f(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".")


def to_gcode(program: PaintProgram, config: MachineConfig) -> str:
    m = config.motion
    surface = config.canvas.surface_z
    brush_index = {b.id: i for i, b in enumerate(config.brushes)}
    lines = [
        "; Generated by painter (PaintProgram -> Klipper)",
        f"; canvas {_f(program.canvas_size[0])} x {_f(program.canvas_size[1])} mm, source: {program.source_image}",
        "; palette slots: " + ", ".join("%d=#%02X%02X%02X" % (c.id, *c.rgb) for c in program.palette),
        "G21 ; mm",
        "G90 ; absolute",
        "PAINTER_START",
        f"G0 Z{_f(m.travel_z)} F{_f(m.z_speed * 60)}",
    ]
    a_pos = 0.0
    brush = None
    for action in program.actions:
        if isinstance(action, ToolChange):
            brush = config.brush(action.brush_id)
            lines.append(f"TOOL_CHANGE BRUSH={brush_index[brush.id]} ; {brush.id}")
            a_pos = 0.0
        elif isinstance(action, Dip):
            lines.append(f"DIP SLOT={action.color_id}")
        elif isinstance(action, Wash):
            lines.append("WASH")
        elif isinstance(action, Wipe):
            lines.append("WIPE")
        elif isinstance(action, Pause):
            slot = "" if action.color_id is None else f" SLOT={action.color_id}"
            lines.append(f"REFILL_PAUSE{slot} ; {action.reason}")
        elif isinstance(action, Paint):
            s = action.stroke
            if brush is None or brush.id != s.brush_id:
                raise ValueError(f"stroke uses {s.brush_id} but the head holds {brush and brush.id}")
            # Pick the equivalent start angle nearest to the current A to avoid needless spinning, but keep it
            # within +-180 deg so the rotation axis never winds up its cable over thousands of strokes.
            period = 180.0 if brush.kind == "flat" else 360.0
            first = s.points[0].angle
            offset = round((a_pos - first) / period) * period
            while first + offset > 180.0:
                offset -= period
            while first + offset < -180.0:
                offset += period
            p0 = s.points[0]
            x0, y0 = config.canvas_to_machine(p0.x, p0.y)
            lines.append(f"; stroke layer={s.layer} color={s.color_id}")
            lines.append(f"G0 X{_f(x0)} Y{_f(y0)} A{_f(first + offset)} F{_f(m.travel_speed * 60)}")
            lines.append(f"G0 Z{_f(surface + m.hover_z)} F{_f(m.z_speed * 60)}")
            for p in s.points:
                x, y = config.canvas_to_machine(p.x, p.y)
                z = surface - p.pressure * brush.press_depth
                lines.append(f"G1 X{_f(x)} Y{_f(y)} Z{_f(z)} A{_f(p.angle + offset)} F{_f(p.speed * 60)}")
            a_pos = s.points[-1].angle + offset
            lines.append(f"G0 Z{_f(m.travel_z)} F{_f(m.z_speed * 60)}")
    lines.append("PAINTER_END")
    return "\n".join(lines) + "\n"
